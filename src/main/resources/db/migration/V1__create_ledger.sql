CREATE TABLE clients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    status VARCHAR(10) NOT NULL CHECK (status IN ('ACTIVE', 'INACTIVE'))
);
CREATE TABLE funds (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    client_id BIGINT NOT NULL REFERENCES clients(id),
    name VARCHAR(120) NOT NULL,
    description VARCHAR(500),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_fund_name UNIQUE (client_id, name),
    CONSTRAINT uk_fund_client_id UNIQUE (client_id, id)
);
CREATE TABLE investors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    client_id BIGINT NOT NULL REFERENCES clients(id),
    name VARCHAR(120) NOT NULL,
    email VARCHAR(254) NOT NULL CHECK (email = LOWER(TRIM(email))),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_investor_email UNIQUE (client_id, email),
    CONSTRAINT uk_investor_client_id UNIQUE (client_id, id)
);
CREATE TABLE fund_participations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    client_id BIGINT NOT NULL REFERENCES clients(id),
    fund_id BIGINT NOT NULL,
    investor_id BIGINT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_participation UNIQUE (client_id, fund_id, investor_id),
    CONSTRAINT fk_participation_fund FOREIGN KEY (client_id, fund_id) REFERENCES funds(client_id, id),
    CONSTRAINT fk_participation_investor FOREIGN KEY (client_id, investor_id) REFERENCES investors(client_id, id)
);
CREATE TABLE ledger_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    client_id BIGINT NOT NULL REFERENCES clients(id),
    fund_id BIGINT NOT NULL,
    investor_id BIGINT NOT NULL,
    transaction_type VARCHAR(30) NOT NULL CHECK (transaction_type IN
        ('CONTRIBUTION', 'INTEREST_INCOME', 'DISTRIBUTION', 'GENERAL_EXPENSE', 'MANAGEMENT_FEE')),
    amount NUMERIC(19, 2) NOT NULL CHECK (amount > 0),
    transaction_date DATE NOT NULL,
    description VARCHAR(500),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_transaction_participation FOREIGN KEY (client_id, fund_id, investor_id)
        REFERENCES fund_participations(client_id, fund_id, investor_id)
);
-- Deliberately no FK to ledger_transactions: retain evidence after financial record deletion.
CREATE TABLE transaction_audits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    transaction_id BIGINT NOT NULL,
    operation VARCHAR(10) NOT NULL CHECK (operation IN ('CREATE', 'UPDATE', 'DELETE')),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_participation_investor ON fund_participations(client_id, investor_id, fund_id);
CREATE INDEX ix_transaction_fund_date ON ledger_transactions(client_id, fund_id, transaction_date, id);
CREATE INDEX ix_transaction_investor_date ON ledger_transactions(client_id, investor_id, transaction_date, id);
CREATE INDEX ix_transaction_client_date ON ledger_transactions(client_id, transaction_date, id);
CREATE INDEX ix_audit_transaction ON transaction_audits(transaction_id);
